-- Font / text overlay
swayimg.text.set_font("JetBrainsMono NF")
swayimg.text.set_size(10)
swayimg.text.set_foreground(0xffcdd6f4) -- #cdd6f4
swayimg.text.set_shadow(0xd0000000) -- #000000d0
swayimg.text.set_background(0x00000000) -- transparent

-- Viewer mode
swayimg.viewer.set_window_background(0xcc11111b) -- #11111bcc
swayimg.viewer.set_image_background(0xcc11111b) -- #11111bcc (transparency bg)
swayimg.viewer.set_default_scale("optimal")
swayimg.viewer.set_default_position("center")
swayimg.enable_antialiasing(true) -- mks13 is default when antialiasing enabled

-- Viewer info text layout
swayimg.viewer.set_text("topleft", {})
swayimg.viewer.set_text("topright", {})
