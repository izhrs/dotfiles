swayimg.gallery.set_thumb_size(200)
swayimg.gallery.limit_cache(100)
swayimg.gallery.enable_preload(false)
swayimg.gallery.enable_pstore(false)
swayimg.gallery.set_aspect("fill")
swayimg.gallery.set_window_color(0xcc11111b) -- #11111bcc
swayimg.gallery.set_unselected_color(0xcc11111b) -- #11111bcc
swayimg.gallery.set_selected_color(0xcc313244) -- #313244cc
swayimg.gallery.set_border_color(0xffb4befe) -- #b4befeff (lavender)

-- Gallery info text layout
